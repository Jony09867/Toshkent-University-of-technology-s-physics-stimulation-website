export function define(key) {
  const c = configs[key],
    words = content[key];
  return {
    ...c,
    key,
    ...words,
    formula: c.formulaLatex,
    levels: Object.fromEntries(
      ["easy", "medium", "hard"].map((l, i) => [
        l,
        {
          params: c.params.filter((p) => p.level <= i),
          render: renderSimulation,
        },
      ]),
    ),
  };
}
export const allConfigs = Object.keys(configs).map(define);
export function defaults(config) {
  return {
    ...Object.fromEntries(config.params.map((p) => [p.key, p.value])),
    ...config.defaults,
  };
}
